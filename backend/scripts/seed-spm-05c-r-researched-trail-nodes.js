async function getFamilyByCode(code) {
  return prisma.spmTrailFamily.findFirst({ where: { code } });
}

async function seedNode(item) {
  const family = await getFamilyByCode(item.familyCode);

  if (!family) {
    console.warn(`[SKIP NODE] ${item.code}: missing family ${item.familyCode}`);
    return { seeded: false, reason: 'missing_family' };
  }

  await prisma.spmTrailNode.upsert({
    where: { code: item.code },
    update: {
      trailFamilyId: family.id,
      trailTrackId: null,
      name: item.name,
      description: item.description,
      nodeType: item.nodeType,
      requirementType: item.requirementType,
      approvalStatus: item.approvalStatus,
      isOfficialNode: Boolean(item.isOfficialNode),
      isCandidateNode: Boolean(item.isCandidateNode),
      isConditionalNode: Boolean(item.isConditionalNode),
      conditionNote: item.decisionClass,
      latitude: null,
      longitude: null,
      locationLabel: null,
      municipality: null,
      barangay: null,
      publicAccessLevel: null,
      stampEligible: Boolean(item.stampEligible),
      bookingRequired: Boolean(item.bookingRequired),
      operatorRequired: Boolean(item.operatorRequired),
      guideRequirement: item.guideRequirement,
      safetyControlled: Boolean(item.safetyControlled),
    },
    create: {
      trailFamilyId: family.id,
      trailTrackId: null,
      code: item.code,
      name: item.name,
      description: item.description,
      nodeType: item.nodeType,
      requirementType: item.requirementType,
      approvalStatus: item.approvalStatus,
      isOfficialNode: Boolean(item.isOfficialNode),
      isCandidateNode: Boolean(item.isCandidateNode),
      isConditionalNode: Boolean(item.isConditionalNode),
      conditionNote: item.decisionClass,
      latitude: null,
      longitude: null,
      locationLabel: null,
      municipality: null,
      barangay: null,
      publicAccessLevel: null,
      stampEligible: Boolean(item.stampEligible),
      bookingRequired: Boolean(item.bookingRequired),
      operatorRequired: Boolean(item.operatorRequired),
      guideRequirement: item.guideRequirement,
      safetyControlled: Boolean(item.safetyControlled),
    },
  });

  console.log(`[SEEDED NODE] ${item.code} -> ${item.name} (${item.decisionClass})`);
  return { seeded: true };
}

async function main() {
  console.log('=== SPM-05C-R researched official trail node seed started ===');

  let seeded = 0;
  let skipped = 0;

  for (const item of researchedNodes) {
    const result = await seedNode(item);
    if (result.seeded) seeded += 1;
    else skipped += 1;
  }

  console.log('');
  console.log('=== Candidate nodes intentionally NOT seeded ===');
  for (const code of blockedCandidateCodes) {
    console.log(`[NOT SEEDED] ${code} -> CANDIDATE_RESEARCH_REQUIRED`);
  }

  console.log('');
  console.log('=== SPM-05C-R seed summary ===');
  console.log(`nodes created/updated: ${seeded}`);
  console.log(`nodes skipped: ${skipped}`);
  console.log(`candidate codes intentionally not seeded: ${blockedCandidateCodes.length}`);
  console.log('=== SPM-05C-R researched official trail node seed complete ===');
}

